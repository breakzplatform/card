#!/usr/bin/env bash
# Regenerates src/avatar.js from the joselito.bio (Gravatar) avatar.
# Development only: needs curl, ImageMagick 7 and Node. The package ships
# the generated module, so the card itself has no dependencies.
set -euo pipefail

avatar_url="https://1.gravatar.com/avatar/8a10eb9cb87d3527f40c6783a9d2b4a36760b60c11a8fe656f23a03b7474f6a3?s=512"
root="$(cd "$(dirname "$0")/.." && pwd)"
workdir="$(mktemp -d)"
trap 'rm -rf "$workdir"' EXIT

curl -fsSL "$avatar_url" -o "$workdir/source"

# Amber "screened" print, as the joseli.to terminal theme asks for imagery:
# grayscale, contrast up, ordered dither, two inks (black and #FFB000).
magick "$workdir/source" \
  -crop 400x400+60+20 +repage -resize 160x160 \
  -colorspace Gray -gamma 0.75 -contrast-stretch 2%x2% \
  -ordered-dither o4x4 +level-colors '#000000,#FFB000' -colors 2 \
  -strip "PNG8:$workdir/avatar.png"

node -e '
const fs = require("node:fs");
const base64 = fs.readFileSync(process.argv[1]).toString("base64");
fs.writeFileSync(process.argv[2], `// Generated by scripts/build-avatar.sh. Do not edit by hand.\nexport const avatarPng = "${base64}";\n`);
' "$workdir/avatar.png" "$root/src/avatar.js"

echo "wrote src/avatar.js ($(wc -c < "$workdir/avatar.png") byte PNG)"
